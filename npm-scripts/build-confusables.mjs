#!/usr/bin/env node
// Builds the spam judge's skeleton table (RFC 041 check 5) from the vendored
// UTS #39 confusables.txt. Each line maps one source code point to its
// prototype; the generated module carries every mapping as one escaped string,
// so a Worker bundles it without reading a file at runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const spamDir = join(repoRoot, "packages", "mailbox-service", "src", "spam");
const source = readFileSync(join(spamDir, "confusables.txt"), "utf8");

const fromHex = (field) =>
	String.fromCodePoint(
		...field
			.trim()
			.split(/\s+/)
			.map((hex) => Number.parseInt(hex, 16)),
	);

const header = source.split("\n").slice(0, 2).join(" ").replace(/#\s*/g, "");
const pairs = source
	.split("\n")
	.map((line) => line.replace(/#.*/, "").trim())
	.filter((line) => line !== "")
	.map((line) => {
		const [from, to] = line.split(";");
		return `${fromHex(from)}\t${fromHex(to)}`;
	});

const escaped = [...pairs.join("\n")]
	.map((char) => {
		const code = char.codePointAt(0);
		if (char === "\t") return "\\t";
		if (char === "\n") return "\\n";
		if (char === '"' || char === "\\") return `\\${char}`;
		if (code >= 0x20 && code < 0x7f) return char;
		return `\\u{${code.toString(16)}}`;
	})
	.join("");

writeFileSync(
	join(spamDir, "confusables-data.ts"),
	`// Generated by npm-scripts/build-confusables.mjs from ${header}. Do not edit.\nexport const CONFUSABLES =\n\t"${escaped}";\n`,
);
console.log(`${pairs.length} mappings`);
